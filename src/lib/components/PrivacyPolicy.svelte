<h2>Privacy Policy for remind-me</h2>

<h3>1. What we collect</h3>
<h4>System Information</h4>
<p>On application startup, information about your device and operating system is automaticly collected. This includes:</p>
<ul>
    <li>The name of the device</li>
    <li>Your platform</li>
    <li>Your operating system</li>
    <li>Your operating system version</li>
    <li>Your processor architecture</li>
</ul>
<h4>Personal Information</h4>
<p>All information entered into the "Create Reminder" Form (Messages and Date), is collected.</p>
<p>On the first start of the application, a UUID (Unique User Identifier) is generated and collected.</p>

<h3>2. How do we use your Data</h3>
<p>We use your Data to provide you the remind-me Service, which is:</p>
<ul>
    <li>The scheduling of Notifications on your Device</li>
    <li>Synchronisation of your Notifications across Devices</li>
</ul>

<h3>3. How we share your Data</h3>
<p>By default, we do not share any of your Data with third parties.</p>
<p>We may share your Personal Data with goverment authorities in compliance with the law or under legal obligations</p>

<h3>4. Retention of Data</h3>
<h4>Data retained until you delete it.</h4>
<p>Certain Information, like your UUID, is retained until you request deletion, after which your Information will be removed in the next 30 Days.</p>
<h4>Data retained until automatic deletion</h4>
<p>Most of the Data is automaticly deleted after a period of time.</p>

<h3>5. Control over your Data</h3>
<p>You have the Right to request all Personal Data currently stored on our Servers by sending an E-Mail to <strong>remind-me@delfi.dev</strong> with the subject <strong>Data Request</strong></p>
<p>You have the Right to delete all Personal Data by sending an E-Mail to <strong>remind-me@delfi.dev</strong> with the subject <strong>Data Deletion Request</strong>, after which your data will be deleted in the next 30 days.</p>

<h3>6. Data Security</h3>
<p>We use commercially reasonable technical measures to protect your data.</p>
<p>However, data transfered over a Internet connection is not fully secure. Therefore we reccomend you take special care when providing Data to our service.</p>

<h3>7. Data Transfer</h3>
<p>All data that you send to us over the Internet is processed and stored on our Servers in Switzerland</p>

<h3>8. Contact</h3>
<p>If you have any further questions or concerns, please contact us by sending an E-Mail to <strong>remind-me@delfi.dev</strong></p>